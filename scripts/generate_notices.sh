#!/usr/bin/env bash
# Generate THIRD_PARTY_NOTICES.md for modules linked into the shipped binaries
# and fail if any dependency uses a license that is incompatible with
# distribution (GPL/AGPL/SSPL). Usage: scripts/generate_notices.sh [output]
set -euo pipefail

cd "$(dirname "$0")/.."
OUT="${1:-THIRD_PARTY_NOTICES.md}"

classify() {
  local file="$1" text
  text="$(head -c 6000 "$file" | tr '[:upper:]' '[:lower:]')"
  case "$text" in
    *"gnu affero general public"*|*"server side public license"*) echo "AGPL/SSPL" ;;
    *"gnu general public license"*) echo "GPL" ;;
    *"gnu lesser general public"*) echo "LGPL" ;;
    *"mozilla public license"*) echo "MPL-2.0" ;;
    *"apache license"*) echo "Apache-2.0" ;;
    *"permission is hereby granted, free of charge"*) echo "MIT" ;;
    *"permission to use, copy, modify, and/or distribute"*|*"permission to use, copy, modify, and distribute"*) echo "ISC" ;;
    *"redistribution and use in source and binary forms"*) echo "BSD" ;;
    *) echo "UNKNOWN" ;;
  esac
}

mods="$(go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}' ./cmd/... | sort -u)"

{
  echo "# Third-Party Notices"
  echo
  echo "Generated by \`scripts/generate_notices.sh\` from modules linked into the"
  echo "FamilyBoard binaries. Do not edit by hand."
  echo
  echo "| Module | Version | License |"
  echo "| --- | --- | --- |"
} > "$OUT"

status=0
while IFS='|' read -r path version dir; do
  [ -z "$path" ] && continue
  lic_file=""
  for cand in LICENSE LICENSE.md LICENSE.txt COPYING LICENCE; do
    if [ -f "$dir/$cand" ]; then lic_file="$dir/$cand"; break; fi
  done
  if [ -z "$lic_file" ]; then
    kind="MISSING"
  else
    kind="$(classify "$lic_file")"
  fi
  echo "| $path | $version | $kind |" >> "$OUT"
  case "$kind" in
    GPL|AGPL/SSPL)
      echo "ERROR: $path ($version) uses disallowed license $kind" >&2
      status=1 ;;
    MISSING|UNKNOWN)
      echo "WARN: $path ($version) license is $kind; review manually" >&2 ;;
  esac
done <<< "$mods"

if [ "$status" -ne 0 ]; then
  echo "License verification FAILED" >&2
  exit "$status"
fi
echo "Wrote $OUT; license verification passed."
